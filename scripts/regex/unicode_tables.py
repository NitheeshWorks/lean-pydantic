"""Generate LeanPydantic/RepoImpl/Regex/Unicode.lean: the code points pydantic's
default regex engine (Rust `regex`) counts as \\d, \\w and \\s.

The tables are measured, not copied: every scalar value is validated against
`constr(pattern=r'^\\d$')` (and \\w, \\s) with the pinned pydantic, and the
accepted code points are written as sorted, disjoint ranges.

Run with: upstream-spec/.venv/bin/python -I scripts/regex/unicode_tables.py
"""
import pathlib
import pydantic
from pydantic import TypeAdapter, ValidationError, constr

OUT = pathlib.Path(__file__).resolve().parents[2] / "LeanPydantic/RepoImpl/Regex/Unicode.lean"


def ranges(pattern):
    ta = TypeAdapter(constr(pattern=pattern))
    out, start = [], None
    for cp in range(0x110000):
        ok = False
        if not 0xD800 <= cp <= 0xDFFF:
            try:
                ta.validate_python(chr(cp))
                ok = True
            except ValidationError:
                pass
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, doc, rs):
    body = ",\n  ".join(", ".join(f"({a:#x}, {b:#x})" for a, b in rs[i:i + 6]) for i in range(0, len(rs), 6))
    return f"/-- {doc} -/\ndef {name} : Array (Nat × Nat) := #[\n  {body}]\n"


def main():
    parts = [
        "/-!\n# RepoImpl: Unicode tables for `\\d`, `\\w` and `\\s`\n\n"
        f"Generated by `scripts/regex/unicode_tables.py` from pydantic {pydantic.VERSION}\n"
        "(Rust `regex`), by testing every scalar value. Do not edit by hand.\n-/\n",
        "namespace LeanPydantic.Regex.Unicode\n",
        table("digit", "`\\d`: Unicode decimal digits (`Nd`).", ranges(r"^\d$")),
        table("word", "`\\w`: Unicode word characters.", ranges(r"^\w$")),
        table("space", "`\\s`: Unicode white space.", ranges(r"^\s$")),
        "end LeanPydantic.Regex.Unicode\n",
    ]
    OUT.write_text("\n".join(parts))


main()
