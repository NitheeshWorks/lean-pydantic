"""Generate LeanPydantic/RepoImpl/Regex/Unicode.lean: the code points pydantic's
default regex engine (Rust `regex`) counts as \\d, \\w and \\s, and its simple
case folding (what `(?i)` matches).

The tables are measured, not copied: every scalar value is validated against
`constr(pattern=r'^\\d$')` (and \\w, \\s) with the pinned pydantic, and the
accepted code points are written as sorted, disjoint ranges. For case folding,
the candidates are the scalar values Rust's `\\p{Cased}`, `\\p{CWCM}` and
`\\p{CWCF}` match together with every one Python's `str` case mappings relate;
each candidate's orbit is the candidates `^(?i)\\x{..}$` matches, and the
script checks that the orbits partition their members and that no other
scalar value matches `(?i)` against any of them, and that `\\d`, `\\w` and `\\s`
hold whole orbits.

Run with: upstream-spec/.venv/bin/python -I scripts/regex/unicode_tables.py
"""
import pathlib
import pydantic
from pydantic import TypeAdapter, ValidationError, constr
from pydantic_core import SchemaValidator

OUT = pathlib.Path(__file__).resolve().parents[2] / "LeanPydantic/RepoImpl/Regex/Unicode.lean"


def ranges(pattern):
    ta = TypeAdapter(constr(pattern=pattern))
    out, start = [], None
    for cp in range(0x110000):
        ok = False
        if not 0xD800 <= cp <= 0xDFFF:
            try:
                ta.validate_python(chr(cp))
                ok = True
            except ValidationError:
                pass
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def scalars():
    return [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]


def validator(pattern):
    return SchemaValidator({'type': 'str', 'pattern': pattern})


def fold_orbits():
    """The simple case-fold orbits with more than one member, as sorted lists."""
    cased = validator(r'^[\p{Cased}\p{Changes_When_Casemapped}\p{Changes_When_Casefolded}]$')
    cand = {cp for cp in scalars() if cased.isinstance_python(chr(cp))}
    for cp in scalars():
        c = chr(cp)
        for m in (c.lower(), c.upper(), c.title(), c.casefold()):
            if len(m) == 1 and m != c:
                cand |= {cp, ord(m)}
    cand = sorted(cand)
    orbit = {}
    for c in cand:
        v = validator('^(?i)\\x{%x}$' % c)
        orbit[c] = tuple(d for d in cand if v.isinstance_python(chr(d)))
    members = {c for c in cand if len(orbit[c]) > 1}
    assert all(orbit[d] == orbit[c] for c in members for d in orbit[c]), 'orbits overlap'
    body = ''.join('\\x{%x}' % c for c in sorted(members))
    anyfold = validator('^(?i)[' + body + ']$')
    assert not [cp for cp in scalars() if cp not in members and anyfold.isinstance_python(chr(cp))], 'orbit missed'
    # \d, \w and \s hold whole orbits, so folding leaves them as they are.
    for cls in (r'\d', r'\w', r'\s'):
        plain, folded = validator('^' + cls + '$'), validator('^(?i)[' + cls + ']$')
        assert all(plain.isinstance_python(chr(cp)) == folded.isinstance_python(chr(cp)) for cp in scalars()), cls
    return sorted({orbit[c] for c in members})


def fold_table(orbits):
    """Each member of an orbit, and the next member (cyclically), sorted by member."""
    pairs = sorted((o[k], o[(k + 1) % len(o)]) for o in orbits for k in range(len(o)))
    # In chunks: one array literal of this size exceeds the elaborator's recursion depth.
    chunks = [pairs[i:i + 600] for i in range(0, len(pairs), 600)]
    out = []
    for n, chunk in enumerate(chunks):
        body = ",\n  ".join(", ".join(f"({a:#x}, {b:#x})" for a, b in chunk[i:i + 6]) for i in range(0, len(chunk), 6))
        out.append(f"/-- `foldNext`, part {n}. -/\ndef foldNext{n} : Array (Nat × Nat) := #[\n  {body}]\n")
    out.append("/-- Simple case folding: every character with a case variant, and the next\n"
               "variant (cyclically) of its orbit, sorted by the first. An orbit has at most\n"
               "four members. -/\n"
               "def foldNext : Array (Nat × Nat) :=\n  "
               + " ++ ".join(f"foldNext{n}" for n in range(len(chunks))) + "\n")
    return "\n".join(out)


def table(name, doc, rs):
    body = ",\n  ".join(", ".join(f"({a:#x}, {b:#x})" for a, b in rs[i:i + 6]) for i in range(0, len(rs), 6))
    return f"/-- {doc} -/\ndef {name} : Array (Nat × Nat) := #[\n  {body}]\n"


def main():
    parts = [
        "/-!\n# RepoImpl: Unicode tables for `\\d`, `\\w`, `\\s` and `(?i)`\n\n"
        f"Generated by `scripts/regex/unicode_tables.py` from pydantic {pydantic.VERSION}\n"
        "(Rust `regex`), by testing every scalar value. Do not edit by hand.\n-/\n",
        "namespace LeanPydantic.Regex.Unicode\n",
        table("digit", "`\\d`: Unicode decimal digits (`Nd`).", ranges(r"^\d$")),
        table("word", "`\\w`: Unicode word characters.", ranges(r"^\w$")),
        table("space", "`\\s`: Unicode white space.", ranges(r"^\s$")),
        fold_table(fold_orbits()),
        "end LeanPydantic.Regex.Unicode\n",
    ]
    OUT.write_text("\n".join(parts))


main()
